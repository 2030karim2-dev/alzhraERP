/**
 * مولد مفاتيح Idempotency لمنع التكرار (نقرة مزدوجة / إعادة محاولة / مزامنة أوفلاين).
 *
 * القاعدة الحاكمة: المفتاح يُولَّد **مرة واحدة لكل نية مستخدم** (فتح نموذج / بدء دفعة)
 * ويُعاد توليده فقط بعد نجاح العملية أو إلغائها. بذلك:
 * - النقر المزدوج على «حفظ» → نفس المفتاح → قيد UNIQUE(company_id, idempotency_key)
 *   في قاعدة البيانات يرفض الفاتورة الثانية (خطأ 23505) بدل إنشائها.
 * - إعادة محاولة الشبكة داخل نفس النية → نفس المفتاح.
 * - إعادة تشغيل طابور الأوفلاين (sync-store) → نفس المفتاح لأنه محفوظ داخل variables
 *   المتسلسلة (persisted) وليس مولَّداً عند كل استدعاء.
 *
 * ⚠️ لا يُستدعَ داخل mutationFn أو داخل طبقة API عند كل استدعاء — ذلك يُبطل الضمانة.
 * طبقة API تقبل مفتاحاً اختيارياً وتولّد واحتياطياً فقط للمتصلين القدامى.
 */
export const createIdempotencyKey = (scope: string): string => {
  const unique = globalThis.crypto?.randomUUID?.() ?? Math.random().toString(36).slice(2);
  return `${scope}_${Date.now()}_${unique}`;
};
